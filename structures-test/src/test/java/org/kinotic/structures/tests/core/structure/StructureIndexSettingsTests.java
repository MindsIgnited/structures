package org.kinotic.structures.tests.core.structure;

import java.io.IOException;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.Test;
import org.kinotic.continuum.idl.api.schema.DateC3Type;
import org.kinotic.continuum.idl.api.schema.ObjectC3Type;
import org.kinotic.continuum.idl.api.schema.StringC3Type;
import org.kinotic.structures.api.domain.Structure;
import org.kinotic.structures.api.domain.idl.decorators.AutoGeneratedIdDecorator;
import org.kinotic.structures.api.domain.idl.decorators.EntityDecorator;
import org.kinotic.structures.api.domain.idl.decorators.EntityType;
import org.kinotic.structures.api.domain.idl.decorators.TimeReferenceDecorator;
import org.kinotic.structures.api.services.ApplicationService;
import org.kinotic.structures.api.services.StructureService;
import org.kinotic.structures.sql.domain.Migration;
import org.kinotic.structures.sql.domain.MigrationContent;
import org.kinotic.structures.sql.executor.MigrationExecutor;
import org.kinotic.structures.sql.parsers.MigrationParser;
import org.kinotic.structures.support.elastic.ElasticTestBase;
import org.kinotic.structures.tests.core.support.TestHelper;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;

import co.elastic.clients.elasticsearch.ElasticsearchClient;
import co.elastic.clients.elasticsearch.indices.GetIndicesSettingsResponse;
import co.elastic.clients.elasticsearch.indices.IndexSettings;

/**
 * Checks that the indexes Structures creates get the shards and replicas configured by elasticNumberOfShards and
 * elasticNumberOfReplicas rather than the defaults: a published structure's index, the backing index of a published
 * stream structure's data stream, and a table created by a project migration.
 * The system indexes are created once per test run, before any test's settings apply, so they are not checked here.
 */
@SpringBootTest(properties = {
        "structures.elastic-number-of-shards=2",
        "structures.elastic-number-of-replicas=0"
})
public class StructureIndexSettingsTests extends ElasticTestBase {

    @Autowired
    private ApplicationService applicationService;
    @Autowired
    private ElasticsearchClient client;
    @Autowired
    private MigrationExecutor migrationExecutor;
    @Autowired
    private MigrationParser migrationParser;
    @Autowired
    private StructureService structureService;
    @Autowired
    private TestHelper testHelper;

    @Test
    public void testPublishedStructureIndexUsesConfiguredShardsAndReplicas() throws IOException {
        Structure structure = testHelper.createAndVerify().getStructure();
        try {
            assertConfiguredShardsAndReplicas(indexSettings(structure.getItemIndex()));
        } finally {
            unPublishAndDelete(structure);
        }
    }

    @Test
    public void testPublishedStreamStructureBackingIndexUsesConfiguredShardsAndReplicas() throws IOException {
        Structure structure = createAndPublishStreamStructure("IndexSettingsStream_" + System.currentTimeMillis());
        try {
            Assertions.assertTrue(structure.isStream());
            // Settings asked for by data stream name come back keyed by its backing indexes. Not using the get data
            // stream API, since this client cannot decode the test cluster's answer to it.
            GetIndicesSettingsResponse response = client.indices()
                                                        .getSettings(b -> b.index(structure.getItemIndex()));
            Assertions.assertEquals(1, response.result().size());
            String backingIndex = response.result().keySet().iterator().next();
            Assertions.assertTrue(backingIndex.startsWith(".ds-" + structure.getItemIndex()),
                                  "Expected a data stream backing index, but got " + backingIndex);

            assertConfiguredShardsAndReplicas(response.get(backingIndex).settings().index());
        } finally {
            unPublishAndDelete(structure);
        }
    }

    @Test
    public void testCreateTableMigrationUsesConfiguredShardsAndReplicas() throws Exception {
        String tableName = "index_settings_table_" + System.currentTimeMillis();
        Migration migration = new Migration() {
            private MigrationContent content;
            @Override public Integer getVersion() { return 1; }
            @Override public String getName() { return "V1__create_" + tableName; }
            @Override public MigrationContent getContent() {
                if (content == null) {
                    content = migrationParser.parse("CREATE TABLE " + tableName + " (id KEYWORD, name TEXT);");
                }
                return content;
            }
        };

        migrationExecutor.executeProjectMigrations(List.of(migration), "test_project_" + tableName).get();
        try {
            assertConfiguredShardsAndReplicas(indexSettings(tableName));
        } finally {
            client.indices().delete(b -> b.index(tableName));
        }
    }

    private Structure createAndPublishStreamStructure(String name) {
        ObjectC3Type entityDefinition = new ObjectC3Type()
                .setName("Reading")
                .setNamespace("org.kinotic.sample")
                .addProperty("id", new StringC3Type(), List.of(new AutoGeneratedIdDecorator()))
                .addProperty("sensor", new StringC3Type())
                .addProperty("readAt", new DateC3Type(), List.of(new TimeReferenceDecorator()));
        entityDefinition.addDecorator(new EntityDecorator().setEntityType(EntityType.STREAM));

        Structure structure = new Structure();
        structure.setName(name)
                 .setApplicationId("org.kinotic.sample")
                 .setProjectId("org.kinotic.sample_default")
                 .setDescription("A stream of sensor readings")
                 .setEntityDefinition(entityDefinition);

        Structure saved = applicationService.createApplicationIfNotExist("org.kinotic.sample", "Sample application")
                                            .thenCompose(v -> structureService.create(structure))
                                            .join();
        structureService.publish(saved.getId()).join();
        return structureService.findById(saved.getId()).join();
    }

    private IndexSettings indexSettings(String indexName) throws IOException {
        return client.indices()
                     .getSettings(b -> b.index(indexName))
                     .get(indexName)
                     .settings()
                     .index();
    }

    private void unPublishAndDelete(Structure structure) {
        structureService.unPublish(structure.getId())
                        .thenCompose(v -> structureService.deleteById(structure.getId()))
                        .join();
    }

    private static void assertConfiguredShardsAndReplicas(IndexSettings settings) {
        Assertions.assertEquals("2", settings.numberOfShards());
        Assertions.assertEquals("0", settings.numberOfReplicas());
    }
}
